"""Seed variation of arms A, C, D: mean and sd over seeds, and every headline gap against 2 sd (PLAN step 10, STAT-1).

usage: uv run python scripts/seeds_table.py [Qwen2.5-3B] [--seeds 0 1 2] [--arms A C D]

Reads results/curriculum_<tag>_<arm>_p200.json (seed 0, the section 15 rerun) and
results/curriculum_<tag>_<arm>_s<seed>_p200.json (SEED=<seed> runs of exp_curriculum.py), all trained
with periodic evaluation, same recipe. Writes reports/seeds_<tag>.md: per metric, the mean +- sd per arm
over seeds and the seed-0 value; then the headline gaps of REPORT.md sections 8 and 15 (C minus A, D minus C,
C minus base, ...) as mean difference, the sd of the difference (sqrt of the two arms' variances), and whether
the gap exceeds 2 sd. The original seed-0 runs (results/curriculum_<tag>_<arm>.json, sections 8) are listed as
a same-seed replicate column: the run-to-run noise at a fixed seed.
"""
import argparse
import json
import math

from ai_experiments.paths import ROOT

METRICS = [("L1_recall_fmt", "recall, trained fmt"), ("L1_recall", "recall, bare"), ("L2_manip_isa", "yes/no"),
           ("L2_manip_pair", "pair"), ("L3_induct_type_nonsense", "Timmy k=3"), ("L3_induct_type_k4", "k=4"),
           ("L4_induct_weakness", "weakness"), ("L4_induct_habitat", "habitat"), ("L3_induct_heldout", "held-out species"),
           ("ICL_symbol_mean", "ICL symbol"), ("ICL_natural_mean", "ICL natural"), ("K_arc_easy", "ARC-Easy"),
           ("L7_ppl_wikitext", "WikiText ppl")]
GAPS = [("C", "A"), ("D", "A"), ("D", "C"), ("C", "base"), ("A", "base"), ("D", "base")]

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("tag", nargs="?", default="Qwen2.5-3B")
ap.add_argument("--seeds", nargs="*", type=int, default=[0, 1, 2])
ap.add_argument("--arms", nargs="*", default=["A", "C", "D"])
a = ap.parse_args()
R = ROOT / "results"


def load(arm, seed):
    p = R / f"curriculum_{a.tag}_{arm}{'' if seed == 0 else f'_s{seed}'}_p200.json"
    return json.loads(p.read_text())["trained"] if p.exists() else None


runs = {arm: {s: load(arm, s) for s in a.seeds} for arm in a.arms}
missing = [(arm, s) for arm in a.arms for s in a.seeds if runs[arm][s] is None]
if missing:
    print("missing runs:", missing)
orig = {arm: json.loads((R / f"curriculum_{a.tag}_{arm}.json").read_text())["trained"] for arm in a.arms
        if (R / f"curriculum_{a.tag}_{arm}.json").exists()}
base = json.loads((R / f"curriculum_{a.tag}_base.json").read_text())["base"]
base_p200 = next((json.loads(p.read_text()) for p in [R / f"curriculum_{a.tag}_A_p200.json"] if p.exists()), {})
base.setdefault("K_arc_easy", base_p200.get("periodic", {}).get("0", {}).get("K_arc_easy"))
if "L7_ppl_wikitext" not in base:
    cp = R / f"corpus_ppl_{a.tag}.json"
    if cp.exists():
        base["L7_ppl_wikitext"] = json.loads(cp.read_text())["results"]["base"]["ppl"]


def stats(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return None, None, 0
    m = sum(vals) / len(vals)
    sd = math.sqrt(sum((v - m) ** 2 for v in vals) / (len(vals) - 1)) if len(vals) > 1 else 0.0
    return m, sd, len(vals)


md = [f"# Seed variation: {a.tag}", "",
      f"Generated by `scripts/seeds_table.py` (PLAN step 10). Seeds {a.seeds} of the section 8 recipe with periodic evaluation; "
      "mean +- sd over seeds (sd with n-1). 'seed 0 (8)' is the original section 8 run of the same seed, a same-seed replicate. "
      "A gap is 'clear' when its absolute mean exceeds 2 sd of the difference (sqrt of the two arms' variances).", ""]
md += ["## Per metric", "", "| metric | " + " | ".join(f"{arm} mean +- sd (n) | {arm} seeds | {arm} seed 0 (8)" for arm in a.arms) + " |",
       "|---|" + "---|" * (3 * len(a.arms))]
summary = {}
for key, name in METRICS:
    row = [name]
    for arm in a.arms:
        vals = [runs[arm][s].get(key) if runs[arm][s] else None for s in a.seeds]
        m, sd, n = stats(vals)
        summary[(arm, key)] = (m, sd, n)
        row += [f"{m:.1f} +- {sd:.1f} ({n})" if m is not None else "", " / ".join("" if v is None else f"{v:g}" for v in vals),
                f"{orig[arm].get(key, ''):g}" if arm in orig and orig[arm].get(key) is not None else ""]
    md.append("| " + " | ".join(row) + " |")
md += ["", "## Headline gaps against 2 sd", "", "| metric | gap | mean diff | sd of diff | 2 sd | clear? |", "|---|---|---|---|---|---|"]
print(f"{'metric':22s} {'gap':10s} {'diff':>7s} {'sd':>6s}  clear")
for key, name in METRICS:
    for x, y in GAPS:
        mx, sdx, nx = summary.get((x, key), (None, None, 0))
        if y == "base":
            my, sdy = base.get(key), 0.0
        else:
            my, sdy, _ = summary.get((y, key), (None, None, 0))
        if mx is None or my is None:
            continue
        d = mx - my
        sd = math.sqrt((sdx or 0) ** 2 + (sdy or 0) ** 2)
        clear = "yes" if abs(d) > 2 * sd and sd > 0 else ("n/a" if sd == 0 else "no")
        md.append(f"| {name} | {x} - {y} | {d:+.1f} | {sd:.1f} | {2 * sd:.1f} | {clear} |")
        print(f"{name:22s} {x + ' - ' + y:10s} {d:+7.1f} {sd:6.1f}  {clear}")
out = ROOT / "reports" / f"seeds_{a.tag}.md"
out.write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)}")
