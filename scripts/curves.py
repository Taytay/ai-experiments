"""Learning curves from periodic evaluation: metric per step per arm (PLAN step 11, TRAIN-3).

usage: uv run python scripts/curves.py [Qwen2.5-3B] [--metrics L1_recall_fmt L3_induct_type_nonsense ...]

Reads the tracker (evals/runs.db): finished `curriculum_v2` runs whose config has `periodic > 0`,
their metrics under condition `periodic` (logged every `periodic` steps, step 0 included, on the
subsample exp_curriculum.py scores mid-training) and the final `trained` row. Writes
reports/curves_<tag>.md, one table per metric with a column per arm and a row per step, and prints
for each arm and metric the step at which the final value was first reached within 2 points.
"""
import argparse
import json
import sqlite3

from ai_experiments.evals.tracker import DB_PATH, ROOT

METRICS = ["L1_recall_fmt", "L3_induct_type_nonsense", "L4_induct_weakness", "ICL_symbol_mean", "K_arc_easy", "L7_ppl_general", "L7_ppl_wikitext"]
LABEL = {"base": "base", "A": "A know", "B": "B epis", "C": "C inter+R", "Cn": "Cn inter", "D": "D seq", "base_m": "base(m)",
         "E": "E morph", "P": "P distill", "Cg": "Cg inter+R+G", "P2": "P2 distill-opt"}

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("tag", nargs="?", default="Qwen2.5-3B")
ap.add_argument("--metrics", nargs="*", default=METRICS)
a = ap.parse_args()

con = sqlite3.connect(DB_PATH)
runs = []
for rid, model, cfg in con.execute("SELECT run_id, model, config FROM runs WHERE experiment='curriculum_v2' AND status='finished' ORDER BY started_at"):
    c = json.loads(cfg)
    if c.get("periodic", 0) and (model or "").split("/")[-1] == a.tag:
        runs.append((rid, c["arm"], c["periodic"], c.get("steps")))
if not runs:
    raise SystemExit("no finished curriculum_v2 runs with periodic evaluation in the tracker")
latest = {}
for rid, arm, per, steps in runs:  # last run per arm wins
    latest[arm] = (rid, per, steps)
print("arms with curves:", ", ".join(f"{arm} ({rid[:15]}, every {per} of {steps})" for arm, (rid, per, steps) in latest.items()))

curves = {}  # arm -> {step: {metric: value}}
for arm, (rid, per, steps) in latest.items():
    pts = {}
    for name, value, step in con.execute("SELECT name, value, step FROM metrics WHERE run_id=? AND condition='periodic'", (rid,)):
        pts.setdefault(step, {})[name] = value
    for name, value in con.execute("SELECT name, value FROM metrics WHERE run_id=? AND condition='trained' AND step IS NULL", (rid,)):
        pts.setdefault(steps, {})[name] = value  # final full eval as the last point
    curves[arm] = dict(sorted(pts.items()))

arms = list(curves)
steps_all = sorted({s for c in curves.values() for s in c})
md = [f"# Learning curves: {a.tag}", "",
      "Generated by `scripts/curves.py` from the tracker. Rows are optimizer steps; step 0 is the base model on the same "
      "subsample; the last row is the full final evaluation (all items). Mid-training points score a fixed subsample "
      "(every 4th ladder item, every 2nd ICL suite item, all 200 ARC-Easy known-facts items), so they carry more noise "
      "than the final row.", ""]
for m in a.metrics:
    md += [f"## {m}", "", "| step | " + " | ".join(LABEL.get(x, x) for x in arms) + " |", "|---|" + "---|" * len(arms)]
    for s in steps_all:
        row = [curves[x].get(s, {}).get(m) for x in arms]
        if any(v is not None for v in row):
            md.append(f"| {s} | " + " | ".join("" if v is None else f"{v:g}" for v in row) + " |")
    md.append("")
out = ROOT / "reports" / f"curves_{a.tag}.md"
out.write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)}")
for arm in arms:
    final_step = max(curves[arm])
    for m in a.metrics:
        final = curves[arm][final_step].get(m)
        if final is None:
            continue
        reached = next((s for s in sorted(curves[arm]) if curves[arm][s].get(m) is not None and abs(curves[arm][s][m] - final) <= 2), final_step)
        print(f"  {LABEL.get(arm, arm):10s} {m:26s} final {final:7.2f} at step {final_step}; within 2 points from step {reached}")
