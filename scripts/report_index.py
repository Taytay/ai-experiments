"""The section index at the top of reports/REPORT.md (owner, 2026-10-05: refer to sections as "§179 Pinterest research applicability",
with the PLAN rows they cover). Short titles live in reports/report_titles.tsv ("<N>\t<title>", one per section; add a line with every
new section). PLAN rows are read from each PLAN row's Result column (the last cell: "REPORT.md 178: ..."); rows that only mention a
section in their description do not count. Extra rows for a section with no Result-column link go in the tsv as a third column
("196-198, 201-207"). The index is written between the INDEX markers, replacing the previous one.
usage: uv run python scripts/report_index.py
"""
import re
from collections import defaultdict

from ai_experiments.paths import ROOT

REPORT, TITLES, PLAN = ROOT / "reports" / "REPORT.md", ROOT / "reports" / "report_titles.tsv", ROOT / "PLAN.md"
BEGIN, END = "<!-- SECTION INDEX: generated by scripts/report_index.py; edit reports/report_titles.tsv -->", "<!-- END SECTION INDEX -->"


def ranges(rows):
    """[171, 172, 173, 180] -> "171-173, 180" """
    out, rows = [], sorted(rows)
    for r in rows:
        if out and r == out[-1][1] + 1:
            out[-1][1] = r
        else:
            out.append([r, r])
    return ", ".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)


if __name__ == "__main__":
    rows_of = defaultdict(set)
    for line in PLAN.read_text().splitlines():
        m = re.match(r"^\| (\d+) \|", line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        result = cells[-1] if cells else ""
        for n in re.findall(r"(?:REPORT(?:\.md)?\s*§?\s*|§)(\d+)", result):
            rows_of[int(n)].add(int(m.group(1)))
    titles, extra = {}, {}
    for line in TITLES.read_text().splitlines():
        if line.strip():
            parts = line.split("\t")
            titles[int(parts[0])] = parts[1].strip()
            if len(parts) > 2 and parts[2].strip():
                extra[int(parts[0])] = parts[2].strip()
    text = REPORT.read_text()
    sections = [int(n) for n in re.findall(r"^## (\d+)\.", text, re.M)]
    missing = [n for n in sections if n not in titles]
    lines = [BEGIN, "", "## Section index", "",
             "Sections are cited as §N plus their short title, e.g. \"§179 Pinterest research applicability\"; the PLAN rows each covers are in brackets.", ""]
    for n in sections:
        rows = extra.get(n) or (ranges(rows_of[n]) if rows_of.get(n) else "")
        word = "rows" if ("-" in rows or "," in rows) else "row"
        lines.append(f"- §{n} {titles.get(n, '(untitled)')}" + (f" ({word} {rows})" if rows else ""))
    lines += ["", END]
    block = "\n".join(lines)
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        at = text.index("\n## 1. ")
        text = text[:at] + "\n" + block + "\n" + text[at:]
    REPORT.write_text(text)
    print(f"{len(sections)} sections indexed; {sum(1 for n in sections if rows_of.get(n) or extra.get(n))} with PLAN rows; untitled: {missing}")
